import {test} from 'node:test';
import assert from 'node:assert/strict';
import {matchPlace} from '../matching.js';
const today='2026-10-27';
const base={policy:{verifiedOn:today,sourceUrl:'https://example.org/policy',maxKg:20,inclusive:true,zones:{indoor:true,outdoor:false}}};
const run=(p,w=16,z='indoor')=>matchPlace(p,{weight:w,zone:z},today).state;
test('20kg 이하 경계와 초과',()=>{assert.equal(run(base,20),'conditional');assert.equal(run(base,20.1),'excluded')});
test('20kg 미만 경계',()=>assert.equal(run({policy:{...base.policy,inclusive:false}},20),'excluded'));
test('미수집 체중 제한은 무제한이 아니다',()=>assert.equal(run({policy:{...base.policy,maxKg:null}}),'unknown'));
test('공간별 허용 여부',()=>{assert.equal(run(base,16,'outdoor'),'excluded');assert.equal(run({policy:{...base.policy,zones:{}}}),'unknown')});
test('오래된/미래/충돌/출처없는 규정',()=>{for(const patch of [{verifiedOn:'2026-01-01'},{verifiedOn:'2027-01-01'},{conflict:true},{sourceUrl:null}])assert.equal(run({policy:{...base.policy,...patch}}),'unknown')});
test('명시적인 무게 제한 없음',()=>assert.equal(run({policy:{...base.policy,maxKg:null,unlimited:true}},60),'conditional'));
test('잘못된 입력과 미검증 장소',()=>{for(const w of [0,-1,NaN,151])assert.equal(run(base,w),'invalid');assert.equal(run({}),'unknown')});
test('공간 무관 검색도 허용 공간이 하나는 확인되어야 한다',()=>assert.equal(run({policy:{...base.policy,zones:{}}},16,'any'),'unknown'));
